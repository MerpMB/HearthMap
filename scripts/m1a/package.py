"""M1A: assemble the QGIS review package and the committed validation report.

outputs/m1a/hearthmap-m1a.gpkg            all verified/acquired layers (EPSG:32647)
outputs/m1a/provenance/<layer>.json       per-layer provenance sidecars
outputs/m1a/hearthmap-m1a.gpkg.provenance.json   package-level provenance
docs/research/m1a-validation-report.md    statistics (text only, committed)

Only layers actually built from acquired data are included; no placeholders.
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

import pyogrio

sys.path.insert(0, str(Path(__file__).parent))
from common import OUTPUT_DIR, OUTPUT_GPKG, PROCESSED, VALIDATION

from hearthmap.enums import Confidence
from hearthmap.ingestion.acquire import RawManifest
from hearthmap.provenance import ProvenanceRecord, current_code_version

LAYERS = [
    ("boundaries", "province_boundaries"),
    ("boundaries", "district_boundaries"),
    ("boundaries", "boundary_reference_differences"),
    ("grid", "analysis_grid_500m"),
    ("dem", "dem_preview_metadata"),
    ("dem", "terrain_preview_500m"),
    ("layers", "flood_recurrence"),
    ("layers", "forest_reserve_screening"),
    ("layers", "national_park_screening"),
    ("layers", "wildlife_sanctuary_screening"),
    ("layers", "major_roads"),
    ("layers", "minor_roads"),
    ("layers", "waterways"),
    ("overlays", "screening_overlays_500m"),
]


def main() -> int:
    if OUTPUT_GPKG.exists():
        OUTPUT_GPKG.unlink()
    prov_dir = OUTPUT_DIR / "provenance"
    if prov_dir.exists():
        shutil.rmtree(prov_dir)
    prov_dir.mkdir(parents=True)

    sources, transforms, counts = {}, [], {}
    for gpkg, layer in LAYERS:
        src = PROCESSED / f"{gpkg}.gpkg"
        df = pyogrio.read_dataframe(src, layer=layer)
        pyogrio.write_dataframe(
            df, OUTPUT_GPKG, layer=layer, driver="GPKG", append=OUTPUT_GPKG.exists()
        )
        counts[layer] = len(df)
        side = PROCESSED / "provenance" / f"{gpkg}.{layer}.provenance.json"
        rec = ProvenanceRecord.from_json(side.read_text(encoding="utf-8"))
        (prov_dir / f"{layer}.provenance.json").write_text(rec.to_json() + "\n", "utf-8")
        for s in rec.sources:
            sources.setdefault(s.source_id, s)
        transforms += [t for t in rec.crs_transformations if t not in transforms]
        print(layer, len(df), flush=True)

    pkg = ProvenanceRecord(
        artifact_id="m1a-review-package",
        artifact_path=OUTPUT_GPKG.as_posix(),
        code_version=current_code_version(),
        sources=list(sources.values()),
        normalized_crs="EPSG:32647",
        method="Assembly of M1A NORMALIZED/DERIVED layers for human review in QGIS. "
        "Per-layer provenance in outputs/m1a/provenance/.",
        spatial_resolution="Mixed; see per-layer records",
        confidence=Confidence.LOW,
        limitations=[
            "GEOMETRY TRUTH, NOT DECISION TRUTH: no suitability score, ranking or "
            "recommendation exists in this package.",
            "Forest/protected layers are screening evidence requiring legal verification.",
        ],
        crs_transformations=transforms,
    ).with_step("assemble", "copy layers into one GeoPackage", layers=counts)
    pkg.write_sidecar(OUTPUT_GPKG)

    # ---------------------------------------------------------------- report
    b = json.loads((VALIDATION / "boundaries.json").read_text("utf-8"))
    g = json.loads((VALIDATION / "grid.json").read_text("utf-8"))
    d = json.loads((VALIDATION / "dem.json").read_text("utf-8"))
    lay = json.loads((VALIDATION / "layers.json").read_text("utf-8"))
    lines = [
        "# M1A validation report",
        "",
        "Generated by `scripts/m1a/package.py` from `data/interim/m1a/validation/*.json` "
        f"(code {current_code_version()[:12]}). **Geometry truth only — nothing is scored.**",
        "",
    ]

    lines += [
        "## 1. Boundaries (PRIMARY: `boundaries-ocha-cod-ab`)",
        "",
        f"- National features: admin1 {b['primary']['national_feature_counts']['admin1']}, "
        f"admin2 {b['primary']['national_feature_counts']['admin2']}; AOI: "
        f"{b['primary']['aoi_feature_counts']['admin1']} provinces, "
        f"{b['primary']['aoi_feature_counts']['admin2']} districts",
        f"- Source CRS {b['primary']['source_crs']} → normalised {b['primary']['normalized_crs']} "
        f"({b['primary']['transformation']['operation']}; datum change: "
        f"{b['primary']['transformation']['datum_change']})",
        f"- Geometry validity (source): admin1 {b['primary']['geometry_validity_source']['admin1']}; "
        f"admin2 {b['primary']['geometry_validity_source']['admin2']}",
        f"- BBox lon/lat: {b['primary']['bbox_lonlat']}; UTM 47N: {b['primary']['bbox_utm47n']}",
        "",
        "| P-code | Province | Thai | Area km² (UTM 47N) | Area km² (attribute) | Δ % | Districts | District overlap km² | Province vs district-union Δ km² |",
        "|---|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    names = {r["adm1_pcode"]: r for r in b["primary"]["names_and_codes"]}
    for pc, r in b["primary"]["per_province"].items():
        lines.append(
            f"| {pc} | {r['name']} | {names[pc]['adm1_name1']} | {r['area_km2_computed_utm47n']:,} | "
            f"{r['area_km2_attribute']:,} | {r['area_attribute_diff_pct']} | {r['district_count']} | "
            f"{r['district_overlap_km2']} | {r['province_vs_district_union_symdiff_km2']} |"
        )
    topo = b["primary"]["inter_province_topology"]
    lines += [
        "",
        "Inter-province topology: "
        + "; ".join(
            f"{k}: overlap {v['overlap_area_m2']} m², shared border {v['shared_border_km']} km"
            for k, v in topo["pairs"].items()
        )
        + f"; interior gaps in union: {topo['union_interior_gaps']}.",
        "",
    ]
    lines += [
        "### Code crosswalk (verified)",
        "",
        "| Province | Thai province code | OCHA P-code | ISO 3166-2 | GISTDA PV_CODE match | geoBoundaries ISO match | config match |",
        "|---|---|---|---|---|---|---|",
    ]
    for c in b["code_crosswalk"].values():
        lines.append(
            f"| {c['name']} | {c['thai_province_code']} | {c['ocha_pcode']} | {c['iso_3166_2']} | "
            f"{c['gistda_pv_code_matches']} | {c['geoboundaries_iso_matches']} | {c['config_province_code_matches']} |"
        )
    lines += [
        "",
        "Code systems: the numeric Thai province code (as used by GISTDA `PV_CODE` and the "
        "national province coding) is embedded in OCHA P-codes (`TH` + code) and in ISO 3166-2 "
        "(`TH-` + code). Internal dataset IDs (e.g. geoBoundaries `shapeID`, ArcGIS `FID`) are "
        "not codes and are not used for joins.",
        "",
    ]
    lines += [
        "### Independent references (mismatches recorded, not corrected)",
        "",
        "| Reference | Role | Province | Ref area km² | Area Δ % | Sym. diff % | Boundary offset median / p95 / max (m) | ≤100 m share |",
        "|---|---|---|---:|---:|---:|---|---:|",
    ]
    for ref, v in b["references"].items():
        for pc, c in v["comparison_vs_primary"].items():
            o = c["boundary_offset"]
            lines.append(
                f"| {ref} | {v['role']} | {pc} | {c['reference_area_km2']:,} | {c['area_diff_pct']} | "
                f"{c['symmetric_difference_pct_of_primary']} | {o['median_m']} / {o['p95_m']} / {o['max_m']} | "
                f"{o['share_within_100m']} |"
            )
    lines += [
        "",
        f"GISTDA district counts by PV_CODE: {b['references']['boundaries-gistda-50k']['district_counts']} "
        "(match COD-AB).",
        "",
        f"Gate: `{json.dumps(b['gate'])}`",
        "",
    ]

    lines += [
        "## 2. Analysis grid (500 m, EPSG:32647)",
        "",
        "| Province | Cells | Full | Partial | Majority-assigned | Grid area km² | Boundary area km² | Coverage diff km² |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for pc in ("TH50", "TH56", "TH57"):
        r = g[pc]
        lines.append(
            f"| {r['province']} ({pc}) | {r['number_of_cells']:,} | {r['full_cells']:,} | {r['partial_cells']:,} | "
            f"{r['cells_majority_in_province']:,} | {r['total_grid_area_km2']:,} | {r['boundary_area_km2']:,} | "
            f"{r['coverage_difference_km2']} |"
        )
    a = g["AOI"]
    lines += [
        f"| **AOI** | {a['number_of_cells']:,} | {a['full_cells']:,} | {a['partial_cells']:,} | — | "
        f"{a['total_grid_area_km2']:,} | {a['boundary_area_km2']:,} | {a['coverage_difference_km2']} |",
        "",
        f"Cells touching two provinces: {a['cells_touching_two_provinces']} (counted in each province row). "
        f"Sum of coverage_fraction * cell area = {a['sum_coverage_fraction_area_km2']:,} km² (equals boundary area). "
        f"Cell ids unique: {a['cell_ids_unique']}.",
        "",
    ]

    t = d["aoi_totals"]
    lines += [
        "## 3. DEM (`dem-copernicus-glo30`, DSM)",
        "",
        f"- Native: {d['native']}",
        f"- Tiles: {len(d['tiles'])}; AOI pixels {t['pixels_in_aoi']:,}; nodata in AOI "
        f"{t['nodata_in_aoi']} ({t['nodata_share']:.4%}); min {t['min_m']:.1f} m; max {t['max_m']:.1f} m",
        f"- Anomalies: below 0 m: {t['below_zero']}; above 2,600 m: {t['above_max']}",
        f"- Cells without any DEM pixel centre (tiny edge slivers): {d['cells_without_dem_pixels']}; "
        f"pixels per cell min/median/max: {d['cell_pixel_count_min_median_max']}",
        "- Terrain layer is an **ANALYTICAL PREVIEW** (DSM-derived), not a slope score.",
        "",
    ]

    lines += [
        "## 4. Other layers",
        "",
        "| Layer | Features | Source CRS | Geometry before → after | Notes |",
        "|---|---:|---|---|---|",
    ]
    for k in (
        "flood_recurrence",
        "forest_reserve_screening",
        "national_park_screening",
        "wildlife_sanctuary_screening",
        "major_roads",
        "minor_roads",
        "waterways",
    ):
        v = lay[k]
        note = ""
        if k == "flood_recurrence":
            note = "flood_freq counts " + json.dumps(v["flood_freq_counts"])
        elif k == "forest_reserve_screening":
            note = "declared vs GIS area % (p5/p50/p95) " + json.dumps(
                v["declared_vs_gis_area_pct_quantiles"]
            )
        elif "length_km" in v:
            note = f"{v['length_km']:,} km; " + json.dumps(v["classes"])
        lines.append(
            f"| {k} | {v['features']:,} | {v['source_crs']} | {v['geometry_before']} → "
            f"{v['geometry_after']} | {note} |"
        )
    lines += [
        "",
        "Flood area by recurrence (km²): "
        + json.dumps(lay["flood_recurrence"]["area_km2_by_freq"]),
        "",
        "### Overlay diagnostics (area-based, not centroid)",
        "",
        "| Metric | Cells > 0 | Mean fraction |",
        "|---|---:|---:|",
    ]
    for k, v in lay["overlay_summary"].items():
        if isinstance(v, dict):
            lines.append(f"| {k} | {v['cells_gt0']:,} | {v['mean']} |")
    lines += [
        "",
        f"Cells where observed flooding covers >0 but <5% of the cell: "
        f"{lay['overlay_summary']['narrow_hits_flood']:,} (would be at risk of being missed by centroid sampling).",
        "",
    ]

    lines += [
        "## 5. Acquired RAW artifacts",
        "",
        "| Source | Version | Files | Bytes | First SHA-256 |",
        "|---|---|---:|---:|---|",
    ]
    for sdir in sorted(p for p in Path("data/raw").iterdir() if p.is_dir()):
        for vdir in sorted(p for p in sdir.iterdir() if p.is_dir()):
            m = RawManifest.read(vdir)
            lines.append(
                f"| {m.source_id} | {m.version} | {len(m.artifacts)} | "
                f"{sum(x.size_bytes for x in m.artifacts):,} | `{m.artifacts[0].sha256[:16]}…` |"
            )
    lines += [
        "",
        "Full per-file checksums: `data/raw/<source>/<version>/manifest.json`.",
        "",
        "## 6. Review package",
        "",
        f"`{OUTPUT_GPKG.as_posix()}` layers:",
        "",
    ]
    lines += [f"- `{k}` ({v:,} features)" for k, v in counts.items()]
    Path("docs/research/m1a-validation-report.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )
    print("package + report OK", OUTPUT_GPKG.stat().st_size)
    return 0


if __name__ == "__main__":
    sys.exit(main())
